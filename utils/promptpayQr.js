// utils/promptpayQr.js
// ─────────────────────────────────────────────────────────────────────────
// ตัวช่วยสร้างรูป "QR PromptPay" ให้น้องหนาวสแกนโอนเงินค่าคอมให้ผู้ขายได้เร็วขึ้น
//
// ⚠️ สำคัญมาก — ตัวช่วยนี้ "ไม่ได้โอนเงินให้อัตโนมัติ" นะครับ แค่สร้างรูป QR ที่มียอดเงิน
// ฝังอยู่ในตัวมันเอง (สแกนแล้วแอปธนาคารกรอกยอดให้อัตโนมัติเลย ไม่ต้องพิมพ์เอง) น้องหนาว
// ยังต้อง "สแกนจ่ายจริง" ด้วยแอปธนาคารของตัวเองอยู่ดี เพราะการให้บอทโอนเงินออกจากบัญชี
// ธนาคารจริงได้เองต้องผ่านระบบ Payment Gateway/ธนาคารระดับองค์กร (เช่น Stripe Connect)
// ซึ่งเป็นงานคนละระดับ ต้องมีการยืนยันตัวตน/สัญญาทางธุรกิจเพิ่ม — ตัวช่วยนี้แค่ลดความ
// ยุ่งยากของขั้นตอน "หาเลขพร้อมเพย์ + พิมพ์ยอดเงินเอง" ให้เร็วขึ้นตอนมีผู้ขายเยอะๆ
//
// ใช้ 2 แพ็กเกจสำเร็จรูป:
//   - promptpay-qr: แปลง "เลขพร้อมเพย์ + จำนวนเงิน" เป็น "ข้อความมาตรฐาน Thai QR
//     Payment" (ตามสเปก EMV QR Code ที่ธนาคารแห่งประเทศไทยกำหนด) — ยาวเป็นสตริงตัวเลข/
//     ตัวอักษรผสมกัน แอปธนาคารทุกเจ้าในไทยอ่านรูปแบบนี้ได้หมด
//   - qrcode: แปลงข้อความนั้นให้เป็น "รูปภาพ QR code" จริง (PNG) เอาไปแนบส่งในดิสคอร์ดได้
// ─────────────────────────────────────────────────────────────────────────

const generatePromptPayPayload = require('promptpay-qr');
const QRCode = require('qrcode');

/**
 * สร้างรูป QR PromptPay เป็น Buffer (PNG) — ฝังยอดเงินไว้ในตัว QR เลย สแกนแล้วยอดขึ้น
 * อัตโนมัติในแอปธนาคาร ไม่ต้องพิมพ์เองอีกที
 *
 * @param {string} promptpayId เลขพร้อมเพย์ของผู้ขาย — ตอนนี้ระบบรับตั้งค่าใหม่ได้แค่เบอร์มือถือ
 *   10 หลัก (เช่น "0812345678") เท่านั้น (ตั้งแต่ 21 ก.ย. 2569 เพื่อความปลอดภัย ดูรายละเอียดที่
 *   PROMPTPAY_ID_PATTERN ใน utils/referralStorage.js) — แต่แพ็กเกจ promptpay-qr ที่ใช้ตรงนี้
 *   ยังรองรับเลขบัตรประชาชน 13 หลักอยู่ในตัว เผื่อโค้ดเก่าที่เคยตั้งไว้แบบนั้นก่อนหน้านี้ ยังสร้าง
 *   QR ได้ปกติไม่ต้องแก้อะไรเพิ่ม (ไม่มีตัวไหนบังคับให้ต้องย้ายมาเป็นเบอร์โทรทันที)
 * @param {number} amountThb จำนวนเงินที่จะโอน (หน่วยบาท ไม่ใช่สตางค์ — ต่างจาก Stripe นะครับ)
 * @returns {Promise<Buffer>} รูปภาพ QR code แบบ PNG พร้อมแนบส่งในดิสคอร์ดได้เลย
 */
async function generatePromptPayQrBuffer(promptpayId, amountThb) {
  const payload = generatePromptPayPayload(promptpayId, { amount: amountThb });
  return QRCode.toBuffer(payload, { type: 'png', width: 512, margin: 2 });
}

module.exports = { generatePromptPayQrBuffer };
