// ก่อนแก้ไฟล์นี้ utils/renderPremiumBilling.js เขียนราคาตายตัวไว้ในหน้าเว็บว่า "$2.99/month"
// (การ์ดบัตร) กับ "฿89/month" (การ์ด PromptPay) ซึ่งเป็น "ราคาเก่า" ที่ไม่ตรงกับราคาจริงใน
// Stripe อีกต่อไปแล้ว (ราคาจริงตอนนี้คือ ฿99/เดือน ตามที่ public/pricing.html โชว์) — ลูกค้า
// จ่ายราคาถูกอยู่แล้วเพราะ Stripe เป็นคนคิดเงินจริง แค่ "ตัวหนังสือ" บนหน้าเว็บโชว์เลขผิดมา
// ตลอดโดยไม่มีใครสังเกต เพราะไม่มีใครเทียบ 2 ไฟล์นี้กันตรงๆ — รวมไว้จุดเดียวกันพลาดซ้ำ
//
// 🆕 ทำไมต้องมีราคา USD แยกสำหรับ PayPal: Stripe ไม่รองรับสกุลเงินบาท (THB) กับ PayPal เลย
// (เช็คจากเอกสาร Stripe แล้ว) ในขณะที่ราคาบัตร/PromptPay หลักตั้งเป็น THB (STRIPE_PREMIUM_
// PRICE_ID ใน .env) เลยต้องมีราคา USD อีกชุดสำหรับ PayPal โดยเฉพาะ — สร้างแบบ "inline" ตอน
// เรียก Stripe ตรงๆ (price_data) แทนที่จะต้องไปสร้าง Price ใหม่ในหน้า Stripe Dashboard ก่อน
// ─────────────────────────────────────────────────────────────────────────

// ราคาไทยที่โชว์บนหน้าเว็บ — ต้องตรงกับ public/pricing.html เป๊ะๆ ถ้าขึ้นราคาต้องแก้ 2 ที่นี้
// พร้อมกันเสมอ (ที่นี่ + pricing.html) ไม่งั้นจะกลับไปเป็นปัญหาราคาไม่ตรงแบบเดิมอีก
const PREMIUM_PRICE_THB_DISPLAY = '฿99';

// ฐานราคา PayPal เป็นดอลลาร์ (ยังไม่รวมค่าธรรมเนียม) — หน่วยเป็น "สตางค์ดอลลาร์" (cents)
// เพราะ Stripe API รับเป็นจำนวนเต็มหน่วยเล็กสุดของสกุลเงินเสมอ (329 = $3.29)
const PAYPAL_BASE_USD_CENTS = 329;

// 🆕 [23 ก.ย. 2569] น้องหนาวขอให้ "บวกราคาเพิ่มเผื่อค่าธรรมเนียม PayPal" แทนที่จะยอมโดนหักเอง
// ⚠️⚠️ ตัวเลข 5% นี้เป็นแค่ค่าประมาณตั้งต้น — ผมไม่มีทางรู้ค่าธรรมเนียม PayPal จริงของบัญชี
// Stripe น้องหนาว (ค่าธรรมเนียมจริงจะขึ้นอยู่กับประเทศ/สกุลเงิน/ปริมาณการใช้งานของแต่ละบัญชี
// ไม่เท่ากัน) ก่อนใช้งานจริงต้องเข้าไปเช็คตัวเลขจริงที่ Stripe Dashboard → Settings → Fees
// (หรือหน้า Pricing ของ Stripe) แล้วแก้เลขนี้ให้ตรงก่อนเสมอ — ดู checklist ในเอกสารโปรเจกต์
const PAYPAL_FEE_SURCHARGE_PERCENT = 5;

/** ราคา PayPal จริงที่จะเรียกเก็บ (รวมค่าธรรมเนียมแล้ว) หน่วยเป็นสตางค์ดอลลาร์ */
function getPaypalChargeCents() {
  return Math.round(PAYPAL_BASE_USD_CENTS * (1 + PAYPAL_FEE_SURCHARGE_PERCENT / 100));
}

/** ราคา PayPal แบบข้อความพร้อมโชว์บนหน้าเว็บ เช่น "$3.45" */
function getPaypalDisplayPrice() {
  const dollars = (getPaypalChargeCents() / 100).toFixed(2);
  return `$${dollars}`;
}

module.exports = {
  PREMIUM_PRICE_THB_DISPLAY,
  PAYPAL_BASE_USD_CENTS,
  PAYPAL_FEE_SURCHARGE_PERCENT,
  getPaypalChargeCents,
  getPaypalDisplayPrice,
};
